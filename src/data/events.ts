export function localize(value: LocalizedText, language: Language) {
  return value[language] || value.en;
}

export function eventStart(event: Pick<CalendarEvent, "date" | "startTime">) {
  return new Date(`${event.date}T${event.startTime}:00`);
}

export function formatEventDate(event: CalendarEvent, language: Language) {
  const locale = { en: "en-US", te: "te-IN", ta: "ta-IN", kn: "kn-IN" }[
    language
  ];
  const date = eventStart(event);
  if (Number.isNaN(date.getTime())) return event.date;
  return new Intl.DateTimeFormat(locale, {
    weekday: "short",
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(date);
}
